ALTER TABLE FIXER_LICENSE  ADD CONSTRAINT PK_FIXER_LICENSE  PRIMARY KEY (LICENSE_ID);
ALTER TABLE FIXER_REGION   ADD CONSTRAINT PK_FIXER_REGION   PRIMARY KEY (FIXER_REGION_ID);
ALTER TABLE FIXER_CATEGORY ADD CONSTRAINT PK_FIXER_CATEGORY PRIMARY KEY (FIXER_CATEGORY_ID);

