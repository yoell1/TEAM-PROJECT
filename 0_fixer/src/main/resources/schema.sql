-- ③ 외래키(FK) + 상태값 체크
--------------------------------------------------
ALTER TABLE FIXER_PROFILE ADD CONSTRAINT FK_FIXER_PROFILE_USERS
      FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID);

ALTER TABLE FIXER_LICENSE ADD CONSTRAINT FK_FIXER_LICENSE_PROFILE
      FOREIGN KEY (FIXER_ID) REFERENCES FIXER_PROFILE(USER_ID) ON DELETE CASCADE;

ALTER TABLE FIXER_REGION ADD CONSTRAINT FK_FIXER_REGION_PROFILE
      FOREIGN KEY (FIXER_ID) REFERENCES FIXER_PROFILE(USER_ID) ON DELETE CASCADE;

ALTER TABLE FIXER_CATEGORY ADD CONSTRAINT FK_FIXER_CATEGORY_PROFILE
      FOREIGN KEY (FIXER_ID) REFERENCES FIXER_PROFILE(USER_ID) ON DELETE CASCADE;

ALTER TABLE FIXER_CATEGORY ADD CONSTRAINT FK_FIXER_CATEGORY_CATEGORY
      FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY(CATEGORY_ID);

ALTER TABLE FIXER_PROFILE ADD CONSTRAINT CK_FIXER_APPROVAL
