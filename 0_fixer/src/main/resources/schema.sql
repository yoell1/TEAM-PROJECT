--------------------------------------------------
CREATE TABLE USERS (
    USER_ID          VARCHAR2(30)   NOT NULL,
    USER_NO          NUMBER,
    USER_PWD         VARCHAR2(100)  NOT NULL,
    USER_NAME        VARCHAR2(50)   NOT NULL,
    USER_PNUMBER     VARCHAR2(20),
    USER_EMAIL       VARCHAR2(100),
    USER_ROLE        VARCHAR2(10)   DEFAULT 'USER',
    ACCOUNT_STATUS   VARCHAR2(10)   DEFAULT 'NORMAL',
    USER_CREATED_AT  TIMESTAMP      DEFAULT SYSTIMESTAMP,
    IS_WITHDRAWN     NUMBER(1)      DEFAULT 0,
    WITHDRAWN_AT     TIMESTAMP
);

CREATE TABLE CATEGORY (
    CATEGORY_ID    VARCHAR2(100)  NOT NULL,
    CATEGORY_NO    NUMBER         NOT NULL,
    CATEGORY_ITEM  VARCHAR2(100)  NOT NULL
);

CREATE TABLE FIXER_PROFILE (
    USER_ID              VARCHAR2(30)   NOT NULL,
    FIXER_NO             NUMBER         NOT NULL,
    FIXER_APPROVAL       VARCHAR2(20)   DEFAULT 'PENDING',
    FIXER_APPROVED_AT    TIMESTAMP,
    FIXER_REJECT_REASON  VARCHAR2(500),
    FIXER_INTRO          VARCHAR2(500),
    FIXER_CAREER         VARCHAR2(200)
);

CREATE TABLE FIXER_LICENSE (
    LICENSE_ID    NUMBER         NOT NULL,
    FIXER_ID      VARCHAR2(30)   NOT NULL,
    LICENSE_NAME  VARCHAR2(100)  NOT NULL,
    LICENSE_NO    VARCHAR2(100),
    LICENSE_FILE  VARCHAR2(500)  NOT NULL,
    ISSUED_AT     DATE,
    UPLOADED_AT   TIMESTAMP      DEFAULT SYSTIMESTAMP
);

CREATE TABLE FIXER_REGION (
    FIXER_REGION_ID  NUMBER         NOT NULL,
    FIXER_ID         VARCHAR2(30)   NOT NULL,
    REGION_NAME      VARCHAR2(100)  NOT NULL
);

CREATE TABLE FIXER_CATEGORY (
    FIXER_CATEGORY_ID  NUMBER         NOT NULL,
    FIXER_ID           VARCHAR2(30)   NOT NULL,
    CATEGORY_ID        VARCHAR2(100)  NOT NULL
);

