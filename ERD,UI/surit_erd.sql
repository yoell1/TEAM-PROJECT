-- [1] 내 접수 목록 (페이징 전 기본형)
SELECT R.REQUEST_NO, R.REQUEST_TITLE, C.CATEGORY_NAME,
       R.REQUEST_STATUS, R.VISIT_HOPE_DATE, R.CREATE_DATE
  FROM REQUEST R
  JOIN CATEGORY C ON (R.CATEGORY_NO = C.CATEGORY_NO)
 WHERE R.MEMBER_NO = #{memberNo}
   AND R.STATUS = 'Y'
 ORDER BY R.REQUEST_NO DESC;

-- [2] 접수 상세 + 배정 + 결과 (진행단계 화면용)
SELECT R.REQUEST_NO, R.REQUEST_TITLE, R.SYMPTOM, R.REQUEST_STATUS,
       R.VISIT_ADDRESS, R.VISIT_HOPE_DATE,
       E.ENGINEER_NAME, E.PHONE AS ENGINEER_PHONE, A.VISIT_DATE,
       RS.RESULT_CONTENT, RS.COST, RS.COMPLETE_DATE
  FROM REQUEST R
  LEFT JOIN ASSIGNMENT    A  ON (R.REQUEST_NO = A.REQUEST_NO)
  LEFT JOIN ENGINEER      E  ON (A.ENGINEER_NO = E.ENGINEER_NO)
  LEFT JOIN REPAIR_RESULT RS ON (R.REQUEST_NO = RS.REQUEST_NO)
 WHERE R.REQUEST_NO = #{requestNo};

-- [3] 관리자 - 상태별 접수 현황 집계
SELECT REQUEST_STATUS, COUNT(*) AS CNT
  FROM REQUEST
 WHERE STATUS = 'Y'
 GROUP BY REQUEST_STATUS;

-- [4] 카테고리별 접수 건수 (통계 화면용)
SELECT C.CATEGORY_NAME, COUNT(R.REQUEST_NO) AS CNT
  FROM CATEGORY C
  LEFT JOIN REQUEST R ON (C.CATEGORY_NO = R.CATEGORY_NO AND R.STATUS = 'Y')
 GROUP BY C.CATEGORY_NAME
 ORDER BY CNT DESC;
