/* =========================================================
   1. MEMBER  (회원)
   ========================================================= */
CREATE TABLE MEMBER (
    MEMBER_NO     NUMBER          NOT NULL,
    MEMBER_ID     VARCHAR2(30)    NOT NULL,
    MEMBER_PWD    VARCHAR2(200)   NOT NULL,
    MEMBER_NAME   VARCHAR2(30)    NOT NULL,
    PHONE         VARCHAR2(20),
    EMAIL         VARCHAR2(100),
    ADDRESS       VARCHAR2(300),
    MEMBER_ROLE   CHAR(1)         DEFAULT 'U' NOT NULL,
    ENROLL_DATE   DATE            DEFAULT SYSDATE NOT NULL,
    STATUS        CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_MEMBER      PRIMARY KEY (MEMBER_NO),
    CONSTRAINT UQ_MEMBER_ID   UNIQUE (MEMBER_ID),
    CONSTRAINT CK_MEMBER_ROLE CHECK (MEMBER_ROLE IN ('U', 'A')),
    CONSTRAINT CK_MEMBER_STAT CHECK (STATUS IN ('Y', 'N'))
);

COMMENT ON TABLE  MEMBER              IS '회원';
COMMENT ON COLUMN MEMBER.MEMBER_NO    IS '회원번호 (PK)';
COMMENT ON COLUMN MEMBER.MEMBER_ID    IS '로그인 아이디';
COMMENT ON COLUMN MEMBER.MEMBER_PWD   IS '비밀번호 (암호화 저장)';
COMMENT ON COLUMN MEMBER.MEMBER_ROLE  IS '권한 U:일반회원 / A:관리자';
COMMENT ON COLUMN MEMBER.STATUS       IS 'Y:활성 / N:탈퇴';


/* =========================================================
   2. CATEGORY  (수리 카테고리)
   ========================================================= */
CREATE TABLE CATEGORY (
    CATEGORY_NO    NUMBER         NOT NULL,
    CATEGORY_NAME  VARCHAR2(30)   NOT NULL,
    CONSTRAINT PK_CATEGORY   PRIMARY KEY (CATEGORY_NO),
    CONSTRAINT UQ_CATEGORY   UNIQUE (CATEGORY_NAME)
);

COMMENT ON TABLE  CATEGORY               IS '수리 카테고리';
COMMENT ON COLUMN CATEGORY.CATEGORY_NAME IS '냉장고 / 세탁기 / 에어컨 / 보일러 / TV / 인터넷 등';


/* =========================================================
   3. ENGINEER  (수리기사)
   ========================================================= */
CREATE TABLE ENGINEER (
    ENGINEER_NO      NUMBER        NOT NULL,
    ENGINEER_NAME    VARCHAR2(30)  NOT NULL,
    CATEGORY_NO      NUMBER        NOT NULL,
    PHONE            VARCHAR2(20),
    REGION           VARCHAR2(50),
    ENGINEER_STATUS  CHAR(1)       DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_ENGINEER     PRIMARY KEY (ENGINEER_NO),
    CONSTRAINT FK_ENG_CATEGORY FOREIGN KEY (CATEGORY_NO) REFERENCES CATEGORY (CATEGORY_NO),
    CONSTRAINT CK_ENG_STATUS   CHECK (ENGINEER_STATUS IN ('Y', 'N'))
);

COMMENT ON TABLE  ENGINEER                 IS '수리기사';
COMMENT ON COLUMN ENGINEER.CATEGORY_NO     IS '담당 카테고리 (FK)';
COMMENT ON COLUMN ENGINEER.REGION          IS '담당 지역';
COMMENT ON COLUMN ENGINEER.ENGINEER_STATUS IS 'Y:배정가능 / N:휴무';


/* =========================================================
   4. REQUEST  (수리 접수)  ★ 핵심 테이블
   ========================================================= */
CREATE TABLE REQUEST (
    REQUEST_NO       NUMBER          NOT NULL,
    MEMBER_NO        NUMBER          NOT NULL,
    CATEGORY_NO      NUMBER          NOT NULL,
    REQUEST_TITLE    VARCHAR2(100)   NOT NULL,
    PRODUCT_NAME     VARCHAR2(100),
    SYMPTOM          VARCHAR2(2000)  NOT NULL,
    VISIT_ADDRESS    VARCHAR2(300)   NOT NULL,
    VISIT_HOPE_DATE  DATE,
    REQUEST_STATUS   VARCHAR2(20)    DEFAULT '접수완료' NOT NULL,
    READ_COUNT       NUMBER          DEFAULT 0 NOT NULL,
    CREATE_DATE      DATE            DEFAULT SYSDATE NOT NULL,
    STATUS           CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_REQUEST     PRIMARY KEY (REQUEST_NO),
    CONSTRAINT FK_REQ_MEMBER  FOREIGN KEY (MEMBER_NO)   REFERENCES MEMBER (MEMBER_NO),
    CONSTRAINT FK_REQ_CATE    FOREIGN KEY (CATEGORY_NO) REFERENCES CATEGORY (CATEGORY_NO),
    CONSTRAINT CK_REQ_STATUS  CHECK (REQUEST_STATUS IN ('접수완료', '기사배정', '방문예정', '처리완료', '취소')),
    CONSTRAINT CK_REQ_DEL     CHECK (STATUS IN ('Y', 'N'))
);

COMMENT ON TABLE  REQUEST                 IS '수리 접수';
COMMENT ON COLUMN REQUEST.SYMPTOM         IS '고장 증상 설명';
COMMENT ON COLUMN REQUEST.VISIT_HOPE_DATE IS '방문 희망일시';
COMMENT ON COLUMN REQUEST.REQUEST_STATUS  IS '진행단계 - 접수완료/기사배정/방문예정/처리완료/취소';
COMMENT ON COLUMN REQUEST.STATUS          IS 'Y:정상 / N:삭제';

CREATE INDEX IDX_REQUEST_MEMBER ON REQUEST (MEMBER_NO);
CREATE INDEX IDX_REQUEST_STATUS ON REQUEST (REQUEST_STATUS);


/* =========================================================
   5. REQUEST_IMG  (접수 첨부 사진)
   ========================================================= */
CREATE TABLE REQUEST_IMG (
    IMG_NO       NUMBER         NOT NULL,
    REQUEST_NO   NUMBER         NOT NULL,
    ORIGIN_NAME  VARCHAR2(255)  NOT NULL,
    CHANGE_NAME  VARCHAR2(255)  NOT NULL,
    IMG_PATH     VARCHAR2(255)  NOT NULL,
    IMG_LEVEL    NUMBER         DEFAULT 1 NOT NULL,
    UPLOAD_DATE  DATE           DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_REQUEST_IMG  PRIMARY KEY (IMG_NO),
    CONSTRAINT FK_IMG_REQUEST  FOREIGN KEY (REQUEST_NO) REFERENCES REQUEST (REQUEST_NO) ON DELETE CASCADE,
    CONSTRAINT CK_IMG_LEVEL    CHECK (IMG_LEVEL >= 1)
);

COMMENT ON TABLE  REQUEST_IMG             IS '접수 첨부 사진';
COMMENT ON COLUMN REQUEST_IMG.ORIGIN_NAME IS '사용자가 올린 원본 파일명';
COMMENT ON COLUMN REQUEST_IMG.CHANGE_NAME IS '서버 저장용 변경 파일명';
COMMENT ON COLUMN REQUEST_IMG.IMG_LEVEL   IS '1:대표사진 / 2 이상:상세사진';


/* =========================================================
   6. ASSIGNMENT  (기사 배정)   REQUEST 1 : 1
   ========================================================= */
CREATE TABLE ASSIGNMENT (
    ASSIGN_NO    NUMBER         NOT NULL,
    REQUEST_NO   NUMBER         NOT NULL,
    ENGINEER_NO  NUMBER         NOT NULL,
    VISIT_DATE   DATE,
    ASSIGN_DATE  DATE           DEFAULT SYSDATE NOT NULL,
    ADMIN_MEMO   VARCHAR2(500),
    CONSTRAINT PK_ASSIGNMENT   PRIMARY KEY (ASSIGN_NO),
    CONSTRAINT UQ_ASSIGN_REQ   UNIQUE (REQUEST_NO),
    CONSTRAINT FK_ASG_REQUEST  FOREIGN KEY (REQUEST_NO)  REFERENCES REQUEST (REQUEST_NO) ON DELETE CASCADE,
    CONSTRAINT FK_ASG_ENGINEER FOREIGN KEY (ENGINEER_NO) REFERENCES ENGINEER (ENGINEER_NO)
);

COMMENT ON TABLE  ASSIGNMENT            IS '기사 배정 및 방문 일정';
COMMENT ON COLUMN ASSIGNMENT.VISIT_DATE IS '확정된 방문 일시';
COMMENT ON COLUMN ASSIGNMENT.ADMIN_MEMO IS '관리자 메모';


/* =========================================================
   7. REPAIR_RESULT  (처리 결과)   REQUEST 1 : 1
   ========================================================= */
CREATE TABLE REPAIR_RESULT (
    RESULT_NO       NUMBER          NOT NULL,
    REQUEST_NO      NUMBER          NOT NULL,
    RESULT_CONTENT  VARCHAR2(2000)  NOT NULL,
    USED_PART       VARCHAR2(300),
    COST            NUMBER          DEFAULT 0 NOT NULL,
    COMPLETE_DATE   DATE            DEFAULT SYSDATE NOT NULL,
    CONSTRAINT PK_REPAIR_RESULT PRIMARY KEY (RESULT_NO),
    CONSTRAINT UQ_RESULT_REQ    UNIQUE (REQUEST_NO),
    CONSTRAINT FK_RST_REQUEST   FOREIGN KEY (REQUEST_NO) REFERENCES REQUEST (REQUEST_NO) ON DELETE CASCADE,
    CONSTRAINT CK_RESULT_COST   CHECK (COST >= 0)
);

COMMENT ON TABLE  REPAIR_RESULT           IS '수리 처리 결과';
COMMENT ON COLUMN REPAIR_RESULT.USED_PART IS '사용 부품';
COMMENT ON COLUMN REPAIR_RESULT.COST      IS '수리 비용 (원)';


/* =========================================================
   8. REPAIR_COMMENT  (접수 문의 댓글)
   ========================================================= */
CREATE TABLE REPAIR_COMMENT (
    COMMENT_NO       NUMBER          NOT NULL,
    REQUEST_NO       NUMBER          NOT NULL,
    MEMBER_NO        NUMBER          NOT NULL,
    COMMENT_CONTENT  VARCHAR2(1000)  NOT NULL,
    CREATE_DATE      DATE            DEFAULT SYSDATE NOT NULL,
    STATUS           CHAR(1)         DEFAULT 'Y' NOT NULL,
    CONSTRAINT PK_REPAIR_COMMENT PRIMARY KEY (COMMENT_NO),
    CONSTRAINT FK_CMT_REQUEST    FOREIGN KEY (REQUEST_NO) REFERENCES REQUEST (REQUEST_NO) ON DELETE CASCADE,
    CONSTRAINT FK_CMT_MEMBER     FOREIGN KEY (MEMBER_NO)  REFERENCES MEMBER (MEMBER_NO),
    CONSTRAINT CK_CMT_STATUS     CHECK (STATUS IN ('Y', 'N'))
);

COMMENT ON TABLE  REPAIR_COMMENT        IS '접수 문의 댓글';
COMMENT ON COLUMN REPAIR_COMMENT.STATUS IS 'Y:정상 / N:삭제';


